/** Flatten i18n fields for a single service */
export function getService(id, lang = 'ar') {
  const svc = SERVICES.find((s) => s.id === id)
  if (!svc) return null
  return { ...svc, ...svc.i18n[lang] }
}

/** Flatten i18n fields for all services */
export function getAllServices(lang = 'ar') {
  return SERVICES.map((svc) => ({ ...svc, ...svc.i18n[lang] }))
}

